// Regressions for finite triangles, actual skin pose, and the public host query.
import assert from 'node:assert/strict';
import T from '../viewer/vendor/three.min.js';
import bed from '../viewer/bathymetry.js';
import {diverSkin} from '../viewer/scuba-triangles.mjs';
import {diverContactRig} from '../viewer/scuba-diver.mjs';
import {movingTriangleContact} from '../viewer/diver-mesh-contact.mjs';
import {diverObstacles} from '../viewer/diver-contact.mjs';
import {drawAnimalCollision} from '../viewer/collision-view.mjs';

const near=(x,y)=>assert(Math.abs(x-y)<1e-6);
const face=[[0,0,0],[1,0,0],[0,1,0]],ref=[0,0,1];
const small=[[.70,.70,0],[.90,.70,0],[.70,.90,0]];
assert(!movingTriangleContact(small,small,face,ref),'disjoint coplanar triangles whose bounding boxes overlap');
const touching=small.map(([x,y,z])=>[x-.5,y-.5,z]);
assert(movingTriangleContact(touching,touching,face,ref),'overlapping coplanar triangles');
const wall=touching.map(([x,y,z])=>[x,y,z+.5]);
const up=face.map(([x,y])=>[x,y,1]);
assert(movingTriangleContact(face,up,wall,ref),'small triangle inside a large swept face, clear of all vertex paths');
const wallOutside=wall.map(([x,y,z])=>[x+1,y+1,z]);
assert(!movingTriangleContact(face,up,wallOutside,ref));
const plating=[[-5,-4,0],[5,-4,0],[0,6,0]];
for(const sign of [-1,1]){
  const before=face.map(([x,y])=>[x,y,sign*.02]);
  const after=face.map(([x,y])=>[x,y,-sign*.15]);
  const hit=movingTriangleContact(before,after,plating,[0,0,-sign*.06]);
  assert(hit,'a thin plate catches a fin even when the swept midpoint has crossed it');
  near(hit.normal[2],sign);
  near(hit.fraction,.02/.17);
  assert(!movingTriangleContact(before,before,plating,ref),'clearance on either side remains open');
}
const row=new Float64Array(88);row[3]=-5;row[43]=150;row[48]=5;
const flat=()=>-20,start=diverContactRig(T),peer=diverContactRig(T);
const cave=[-27.5,-30,-45.15];
const higher=start.spawnHeight(cave,Math.PI,0,bed.surfaceHeight.bind(bed));
assert(higher>cave[2]+1.5&&higher<cave[2]+2.5,'prone fin tips clear the steep cave approach');
near(start.spawnHeight([17.1,24.8,-5.9],.7,0,bed.surfaceHeight.bind(bed)),-5.9);
const noWorld=()=>null;noWorld.triangles=()=>{};
const free=start.sample(row,0,flat,noWorld,.1);
assert.equal(free.score,0);assert.deepEqual(free.meshSelfContact,Array(9).fill(0));
const crossed=Float64Array.from(row);crossed[78]=-.10;crossed[80]=.10;
const inner=start.sample(crossed,0,flat,noWorld,.1);
assert.deepEqual(inner.meshSelfContact.slice(0,2).sort((a,b)=>a-b),[6,13]);
assert(inner.meshSelfContact[5]>.002);
const headWall=()=>null;
headWall.triangles=(b,t,dt,emit)=>emit([[.54,-.8,-6],[.54,.8,-6],[.54,0,-4]]);
const head=start.sample(row,0,flat,headWall,.1);
assert.equal(head.part,'head');assert.equal(head.contactLink,1);near(head.contact[0],-1);
row[1]=.45;row[7]=Math.PI;peer.rig.applyFrame(row,0,flat);
const points=peer.rig.triangles.snapshot();
row[1]=0;row[7]=0;
const neighbor=diverObstacles([{id:'other',kind:'diver',x:.45,y:0,z:-5}],'diver',row,.1,noWorld,()=>points);
assert(start.sample(row,0,flat,neighbor,.1).contact[3]>0,'posed diver mesh collides with another diver');
const remote=Float64Array.from(points,(v,i)=>i%3===1?v+1:v);
const clear=diverObstacles([{id:'other',kind:'diver',x:.45,y:1,z:-5}],'diver',row,.1,noWorld,()=>remote);
assert.equal(start.sample(row,0,flat,clear,.1).score,0);
let coordinates=0;
drawAnimalCollision({lines(frame,xyz){assert.equal(frame,null);coordinates+=xyz.length;}},start.rig.group,'diver');
assert.equal(coordinates,18*diverSkin.triangles.length/4);
console.log(diverSkin.vertices.length/4+' rigged vertices, '+diverSkin.triangles.length/4+' triangles; finite/coplanar/continuous intersection, unloaded rest, two opposed fins, peer and world contacts, and debug topology passed.');
