import {execFileSync} from 'node:child_process';
import {readFileSync,writeFileSync} from 'node:fs';
import {join,resolve} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
const [src,out] = process.argv.slice(2);
const {CLANG,LLVM_BIN,CUDA_LIBDEVICE,FMI_INCLUDE,RUMOCA_ROOT,PTXAS} = process.env;
const cuda=join(RUMOCA_ROOT,'examples/codegen/cuda-fmi3');
const {lowerBulkCopies}=await import(pathToFileURL(join(cuda,'bulk-copy.mjs')));
const {lowerLaneWorkspace}=await import(pathToFileURL(join(cuda,'arena.mjs')));
const run=(cmd,...args)=>execFileSync(cmd,args,{stdio:'inherit'});
const arch=process.env.CUDA_ARCH??'sm_86';
const flag=['--target=nvptx64-nvidia-cuda','-march='+arch,'-std=c11','-DRMC_FMI3_INLINE_FACTORS','-DRMC_CUDA_BLOCK_COPIES','-ffreestanding','-I'+join(cuda,'freestanding'),'-I'+resolve(src),'-I'+resolve(out),'-I'+FMI_INCLUDE];
const f=name=>join(out,name);
run(CLANG,...flag,'-O2','-ffp-contract=off','-fno-math-errno','-S','-emit-llvm',fileURLToPath(new URL('rigid.c',import.meta.url)),'-o',f('rigid.ll'));
const ir=readFileSync(f('rigid.ll'),'utf8'), entry=ir.replace(/^define [^\n@]*void @rigid_batch\(/m,'define ptx_kernel void @rigid_batch(');
if(ir===entry) throw Error('Missing kernel entry');
writeFileSync(f('rigid.ll'),entry);
run(join(LLVM_BIN,'llvm-link'),f('rigid.ll'),CUDA_LIBDEVICE,'-o',f('linked.bc'));
run(join(LLVM_BIN,'opt'),'-passes=internalize,globaldce,default<O2>','-internalize-public-api-list=rigid_batch',f('linked.bc'),'-S','-o',f('opt.ll'));
const ws=lowerLaneWorkspace(readFileSync(f('opt.ll'),'utf8'),true);
writeFileSync(f('arena.ll'),lowerBulkCopies(ws.ir));
for(const name of ['bulk-copy','block-copy']) run(CLANG,...flag,'-O2','-emit-llvm','-c',join(cuda,name+'.c'),'-o',f(name+'.bc'));
run(join(LLVM_BIN,'llvm-link'),f('arena.ll'),f('bulk-copy.bc'),f('block-copy.bc'),'-o',f('device.bc'));
run(join(LLVM_BIN,'llc'),'-O2','-mtriple=nvptx64-nvidia-cuda','-mcpu='+arch,'-mattr=+ptx80',f('device.bc'),'-o',f('rigid.ptx'));
run(PTXAS??'ptxas','-O3','-v','-arch='+arch,f('rigid.ptx'),'-o',f('rigid.cubin'));
