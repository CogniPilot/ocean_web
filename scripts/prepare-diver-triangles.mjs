// Reduce the dressed, posed GLB to a material-free collision LOD in bone-local metres.
import {readFile,writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {diverBind} from '../viewer/scuba-bind.mjs';
const T=globalThis.THREE=createRequire(import.meta.url)('../viewer/vendor/three.min.js');
globalThis.self=globalThis;
const {GLTFLoader}=await import('../viewer/vendor/gltf-loader.mjs');
const bytes=await readFile(new URL('../viewer/assets/subsea/scuba-diver.glb',import.meta.url));
const {scene}=await new GLTFLoader().parseAsync(bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength),'');
scene.position.fromArray(diverBind.offset);scene.quaternion.fromArray(diverBind.orientation);scene.updateMatrixWorld(true);
const supported=new Set(diverBind.bones.map(b=>b[0]));
const names=[],lookup=new Map(),cells=[],triangles=[],seen=new Set(),parts=[];
const point=new T.Vector3(),local=new T.Vector3(),origin=new T.Vector3();
function segment(name,p,foot){
  const side=name.endsWith('_r')?7:0;
  if(name.startsWith('thigh'))return [3+side,'leg'];
  if(name.startsWith('calf'))return [4+side,'leg'];
  if(name.startsWith('foot'))return [6+side,p.distanceTo(foot)>.22?'fin':'boot'];
  if(name.startsWith('upperarm'))return [7+side,'arm'];
  if(name.startsWith('lowerarm')||name.startsWith('hand'))return [8+side,name.startsWith('hand')?'hand':'arm'];
  if(name==='Head'||name==='neck_01')return [1,'head'];
  return [1,p.z>.14&&Math.abs(p.y)<.11?'tank':'body'];
}
scene.traverse(mesh=>{
  if(!mesh.isSkinnedMesh)return;
  const {geometry:g,skeleton}=mesh,index=g.index.array;
  const ids=g.attributes.skinIndex,weights=g.attributes.skinWeight;
  const mapped=new Map();
  function vertex(i){
    if(mapped.has(i))return mapped.get(i);
    let best=0;
    for(let j=1;j<4;j++)if(weights.getComponent(i,j)>weights.getComponent(i,best))best=j;
    let bone=skeleton.bones[ids.getComponent(i,best)];
    while(!supported.has(bone.name))bone=bone.parent;
    const name=bone.name;
    let boneId=names.indexOf(name);
    if(boneId<0){boneId=names.length;names.push(name);}
    mesh.localToWorld(mesh.getVertexPosition(i,point));
    const [link,kind]=segment(name,point,bone.getWorldPosition(origin));
    bone.worldToLocal(local.copy(point));
    const fin=kind==='fin'||kind==='boot';
    const keys=[boneId,kind,Math.round(point.x/.10),Math.round(point.y/(fin?.054:.077)),Math.round(point.z/(fin?.024:.077))];
    const key=keys.join('/');
    let cell=lookup.get(key);
    if(cell===undefined){
      cell=cells.length;lookup.set(key,cell);cells.push({boneId,link,kind,total:new T.Vector3(),n:0});
    }
    const c=cells[cell];c.total.add(local);c.n++;mapped.set(i,cell);
    return cell;
  }
  for(let i=0;i<index.length;i+=3){
    const a=vertex(index[i]),b=vertex(index[i+1]),c=vertex(index[i+2]);
    if(a===b||b===c||c===a)continue;
    const key=[a,b,c].sort((x,y)=>x-y).join('/');
    if(seen.has(key))continue;
    seen.add(key);
    const votes=[cells[a],cells[b],cells[c]],part=votes[1].kind===votes[2].kind&&votes[1].link===votes[2].link?votes[1]:votes[0];
    const tag=part.link+'/'+part.kind;
    let label=parts.indexOf(tag);
    if(label<0){label=parts.length;parts.push(tag);}
    triangles.push(a,b,c,label);
  }
});
const vertices=cells.flatMap(c=>[c.boneId,...c.total.divideScalar(c.n).toArray().map(x=>+x.toFixed(5))]);
const target=new URL('../viewer/scuba-triangles.mjs',import.meta.url);
await writeFile(target,'// Generated by scripts/prepare-diver-triangles.mjs from scuba-diver.glb.\nexport const diverSkin='+JSON.stringify({bones:names,vertices,parts,triangles})+';\n');
console.log(cells.length+' rigged vertices, '+triangles.length/4+' collision triangles');
