// Rebuild the authoritative lightweight joint rig from the same dressed GLB as the viewer.
import {readFileSync,writeFileSync} from 'node:fs';
const glb=readFileSync(new URL('../viewer/assets/subsea/scuba-diver.glb',import.meta.url));
const doc=JSON.parse(glb.subarray(20,20+glb.readUInt32LE(12)));
const source=doc.nodes,parents=new Map();
source.forEach((n,i)=>n.children?.forEach(c=>parents.set(c,i)));
const used=new Set();
source.forEach((n,i)=>{
  if(!/^(?:Head|neck_01|spine_0[12]|(?:upperarm|lowerarm|hand|thigh|calf|foot)_[lr])$/.test(n.name))return;
  for(let j=i;j!==undefined;j=parents.get(j))used.add(j);
});
const ids=[...used].sort((a,b)=>a-b);
const bones=ids.map(i=>{
  const n=source[i];
  return [n.name,ids.indexOf(parents.get(i)),n.translation,n.rotation,n.scale,n.extras];
});
const {offset,orientation}=doc.scenes[0].extras;
const clean=(k,v)=>typeof v==='number'?+v.toPrecision(9):v;
writeFileSync(new URL('../viewer/scuba-bind.mjs',import.meta.url),
  '// Generated by scripts/prepare-scuba-contacts.mjs from the dressed diver. Lengths in metres.\n'+
  'export const diverBind='+JSON.stringify({offset,orientation,bones},clean)+';\n');
