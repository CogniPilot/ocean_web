"""Train the view's 2× luminance model on original, procedural patches."""

import argparse
import json
from pathlib import Path
import numpy as np


def examples(seed, count):
    rng = np.random.default_rng(seed)
    # Four samples per target pixel model coverage of subpixel geometry.
    coordinate = np.arange(12, dtype=np.float32) * .25 - 1.375
    x, y = np.meshgrid(coordinate, coordinate)

    def uniform(lo, hi):
        return rng.uniform(lo, hi, (count, 1, 1)).astype(np.float32)

    image = uniform(.15, .85) + uniform(-.09, .09) * x + uniform(-.09, .09) * y
    for _ in range(3):
        angle = uniform(-np.pi, np.pi)
        along = np.cos(angle) * x + np.sin(angle) * y
        image += uniform(0, .13) * np.sin(uniform(.5, 6) * along + uniform(-np.pi, np.pi))
    for _ in range(2):
        angle = uniform(-np.pi, np.pi)
        along = np.cos(angle) * x + np.sin(angle) * y
        across = -np.sin(angle) * x + np.cos(angle) * y
        signed = along - uniform(-1.5, 1.5) + uniform(-.28, .28) * across**2
        softness = uniform(.08, .55)
        size = uniform(.15, 1.8)
        # Mix hard edges, finite-width ropes and highlights.
        edge = np.clip(signed / softness + .5, 0, 1)
        ribbon = np.clip((size - abs(signed)) / softness + .5, 0, 1)
        image += uniform(-.70, .70) * np.where(uniform(0, 1) < .55, edge, ribbon)

    high = image.clip(0, 1).reshape(count, 6, 2, 6, 2).mean(axis=(2, 4))
    low = high.reshape(count, 3, 2, 3, 2).mean(axis=(2, 4))
    center = low[:, 1, 1]
    base = np.stack([(9 * center + 3 * low[:, 1, column] +
                      3 * low[:, row, 1] + low[:, row, column]) / 16
                     for row in (0, 2) for column in (0, 2)], axis=1)
    target = high[:, 2:4, 2:4].reshape(count, 4)
    return (low - center[:, None, None]).reshape(count, 9), target - base


def fit(output, steps):
    rng = np.random.default_rng(42)
    x, target = examples(1201, 65536)
    valid, expected = examples(4612, 8192)
    width = 12
    parameters = [
        rng.normal(0, .28, (9, width)).astype(np.float32),
        np.full(width, .01, dtype=np.float32),
        rng.normal(0, .07, (width, 4)).astype(np.float32),
    ]
    first, offset, last = parameters
    averages = [np.zeros_like(value) for value in parameters]
    variances = [np.zeros_like(value) for value in parameters]
    batch = 512

    def prediction(inputs):
        hidden = inputs @ first + offset
        return hidden, np.maximum(0, hidden) - np.maximum(0, offset)

    for step in range(1, steps + 1):
        rows = rng.integers(0, len(x), batch)
        inputs = x[rows]
        hidden, activation = prediction(inputs)
        error = (activation @ last - target[rows]) / batch
        backward = error @ last.T
        slope = backward * (hidden > 0)
        gradients = [inputs.T @ slope,
                     (slope - backward * (offset > 0)).sum(axis=0),
                     activation.T @ error]
        for value, gradient, average, variance in zip(
                parameters, gradients, averages, variances):
            average[:] = .9 * average + .1 * gradient
            variance[:] = .999 * variance + .001 * gradient**2
            rate = .005 * (.15 + .85 * (1 - step / steps))
            value -= (rate * average / (1 - .9**step) /
                      (np.sqrt(variance / (1 - .999**step)) + 1e-8))

    baseline_mse = np.mean(expected**2)
    network_mse = np.mean((prediction(valid)[1] @ last - expected)**2)
    print(f"Held-out PSNR {10*np.log10(1/baseline_mse):.2f} dB bilinear, "
          f"{10*np.log10(1/network_mse):.2f} dB neural")
    model = {"kernel": first.T, "offset": offset, "residual": last}
    lines = [f"export const {key}={json.dumps(value.astype(float).round(7).tolist(), separators=(',', ':'))};"
             for key, value in model.items()]
    output.write_text("// SPDX-License-Identifier: Apache-2.0\n"
                      "// Generated by scripts/train-neural-upscaler.py.\n" +
                      "\n".join(lines) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--steps", type=int, default=2400)
    parser.add_argument("--output", type=Path, default=Path("viewer/neural-upscaler-model.mjs"))
    options = parser.parse_args()
    fit(options.output, options.steps)
