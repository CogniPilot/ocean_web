// Generate the Modelica contact table from the same primitives used by the viewer.
import {readFileSync,writeFileSync} from 'node:fs';
import {piccardParts,viewport} from '../viewer/piccard-geometry.mjs';
const file=name=>new URL('../'+name,import.meta.url);
const plant=readFileSync(file('Wreck/package.mo'),'utf8');
function table(name){
  return plant.match(new RegExp(name+'\\[6,3\\]=\\[([^\\]]+)\\]'))[1].split(';').map(row=>row.split(',').map(Number));
}
const {parts}=piccardParts(table('propMount'),table('propAxis'));
const rows=parts.map(({center,half,kind,axis})=>[...center,...half,kind==='plate'?0:axis+1].map(x=>+x.toFixed(10)).join(','));
let reach=Math.hypot(...viewport.center)+viewport.radius;
for(const {kind,center,half,axis} of parts){
  if(kind==='plate'){
    reach=Math.max(reach,Math.hypot(...center.map((x,i)=>Math.abs(x)+half[i])));
  }else{
    const u=(axis+1)%3,v=(axis+2)%3;
    reach=Math.max(reach,Math.hypot(Math.abs(center[axis])+half[axis],Math.hypot(center[u],center[v])+half[u]));
  }
}
writeFileSync(file('Wreck/PiccardSolids.mo'),`within Wreck;
package PiccardSolids "Generated by scripts/piccard-solids.mjs from the Piccard body geometry"
  constant Integer count=${parts.length};
  constant Real reach=${Math.ceil(1000*reach)/1000} "Enclosing radius rounded up to millimetres";
  constant Real dome[4]={${[...viewport.center,viewport.radius].join(',')}};
  constant Real primitives[count,7]=[
    ${rows.join(';\n    ')}] "Body centre, axis-aligned half dimensions, cylinder axis (1..3) or 0 for plate";
end PiccardSolids;
`);
