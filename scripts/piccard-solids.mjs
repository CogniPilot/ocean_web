// Serialize the display geometry once so the Modelica contact kernel can
// index an individual primitive without materializing the whole mesh.
import {readFileSync,writeFileSync} from 'node:fs';
import {piccardParts,viewport} from '../viewer/piccard-geometry.mjs';
const file=name=>new URL('../'+name,import.meta.url);
const plant=readFileSync(file('Wreck/package.mo'),'utf8');
function table(name){
  return plant.match(new RegExp(name+'\\[6,3\\]=\\[([^\\]]+)\\]'))[1].split(';').map(row=>row.split(',').map(Number));
}
const {parts}=piccardParts(table('propMount'),table('propAxis'));
function branch(first,last,indent){
  if(first===last){
    const part=parts[first];
    const numbers=[...part.center,...part.half,...part.basis.flat()].map(x=>+x.toFixed(10));
    return indent+'row:={'+numbers.join(',')+'};';
  }
  const mid=Math.floor((first+last)/2);
  return [indent+'if index<='+String(mid+1)+' then',branch(first,mid,indent+'  '),indent+'else',branch(mid+1,last,indent+'  '),indent+'end if;'].join('\n');
}
writeFileSync(file('Wreck/PiccardSolids.mo'),`within Wreck;
package PiccardSolids "Generated by scripts/piccard-solids.mjs from the Piccard body geometry"
  constant Integer count=${parts.length};
  constant Real dome[4]={${[...viewport.center,viewport.radius].join(',')}};
  function getBox
    input Integer index;
    output Real row[15] "Body centre, half dimensions and three body-frame axes";
  algorithm
${branch(0,parts.length-1,'    ')}
  end getBox;
end PiccardSolids;
`);
